/**
 * The nginx configuration for the three HydroXid instances — one server block (= one port) per
 * theme. Same blocks for every target; only ports, paths and the shop upstream differ.
 *
 *   node scripts/render-nginx.mjs local|pay1   →   build/nginx-<target>.conf
 *
 * Each block serves the same compiled app, but its own rendered /oxid-config.json (which names the
 * instance's theme). The deployment YAMLs are not in the web root and answer 404 anyway.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const TARGETS = {
  // the container of docker-compose.yml: app mounted at /srv/hydroxid, the SDK shop on the host
  local: {
    root: '/srv/hydroxid',
    serverName: '_',
    upstream: 'http://host.docker.internal',
    upstreamHost: 'localhost.local',
    tls: false,
  },
  // pay1.oxid.dev: host nginx; the OXID shop's apache container listens on 127.0.0.1:8543 (TLS)
  pay1: {
    root: '/var/www/oxid/oxid75/hydroxid-project/current',
    serverName: 'pay1.oxid.dev',
    upstream: 'https://127.0.0.1:8543',
    upstreamHost: 'pay1.oxid.dev',
    tls: true,
  },
};

function serverBlock(name, port, target) {
  const proxy = (path) => `
    location ${path} {
        proxy_pass ${target.upstream}${path};
        proxy_http_version 1.1;${
          target.tls
            ? `
        proxy_ssl_verify off;
        proxy_ssl_server_name on;`
            : ''
        }
        proxy_set_header Host ${target.upstreamHost};
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_read_timeout 120s;
    }
`;
  return `# instance "${name}"
server {
    listen ${port};
    server_name ${target.serverName};
    root ${target.root}/dist;
    index index.html;

    # the browser's configuration: rendered from instances/${name}/oxid-config.yaml (allow-list + secret guard)
    location = /oxid-config.json {
        alias ${target.root}/build/instances/${name}/oxid-config.json;
        default_type application/json;
        add_header Cache-Control "no-store";
    }

    # deployment YAML is never served
    location ~* \\.ya?ml(\\.dist)?$ {
        return 404;
    }
${proxy('/graphql/')}${proxy('/out/pictures/')}
    location /assets/ {
        add_header Cache-Control "public, max-age=31536000, immutable";
    }

    location / {
        add_header Cache-Control "no-cache";
        try_files $uri $uri/ /index.html;
    }
}
`;
}

export function renderNginx(targets, targetName) {
  const target = TARGETS[targetName];
  if (!target) {
    throw new Error(`unknown target "${targetName}" (${Object.keys(TARGETS).join(', ')})`);
  }
  const entries = Object.entries(targets.instances);
  const ports = entries.map(([, instance]) => instance.ports[targetName]);
  if (new Set(ports).size !== ports.length) {
    throw new Error(`two instances use the same port on ${targetName}`);
  }
  return (
    `# generated by scripts/render-nginx.mjs for ${targetName} — do not edit\n\n` +
    entries
      .map(([name, instance]) => serverBlock(name, instance.ports[targetName], target))
      .join('\n')
  );
}

if (process.argv[1]?.endsWith('render-nginx.mjs') && process.argv[2]) {
  const targetName = process.argv[2];
  const targets = JSON.parse(readFileSync('deploy/instances.json', 'utf-8'));
  mkdirSync('build', { recursive: true });
  writeFileSync(`build/nginx-${targetName}.conf`, renderNginx(targets, targetName));
  console.log(`nginx: build/nginx-${targetName}.conf`);
}
